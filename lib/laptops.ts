/*
 * Laptop GPUs and the machines that ship them.
 *
 * Laptop GPUs share a marketing name with their desktop cousins but are
 * different, cut-down silicon — an "RTX 5080 Laptop" is nowhere near an RTX
 * 5080. More importantly, the SAME laptop GPU performs very differently
 * depending on the power the chassis lets it draw (TGP). A 4060 at 140 W and a
 * 4060 at 65 W are not the same product, which is why every machine below
 * records its own TGP and the finder ranks on the resulting effective figure
 * rather than on the GPU name.
 *
 * Performance figures use the same index as the desktop database
 * (desktop RTX 4090 = 100) so the two are directly comparable.
 */

import type { Brand } from "./gpus";

export interface LaptopGpu {
  id: string;
  name: string;
  short: string;
  brand: Brand;
  generation: string;
  vram: number;
  vramType: string;
  memoryBus: number;
  shaders: number;
  /** Manufacturer-allowed TGP range, excluding Dynamic Boost. */
  minTgp: number;
  maxTgp: number;
  /** 1440p raster index at max TGP, desktop RTX 4090 = 100. */
  perfAtMaxTgp: number;
  /** 1440p ray tracing index at max TGP. */
  rtAtMaxTgp: number;
  /** Desktop card this is loosely comparable to, for cross-referencing. */
  desktopCousin?: string;
  upscaling: string;
}

