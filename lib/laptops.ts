/**
 * Effective performance for a GPU held at a given TGP.
 *
 * Performance scales sub-linearly with power — the last watts buy very little.
 * The 0.35 exponent lands within a few percent of published TGP-scaling tests
 * (a 175 W part cut to 105 W loses roughly 15%), but it is a model, not a
 * measurement of any specific machine.
 */
export function perfAtTgp(perfAtMax: number, tgp: number, maxTgp: number): number {
  const ratio = Math.min(1, tgp / maxTgp);
  return +(perfAtMax * Math.pow(ratio, 0.35)).toFixed(1);
}

export interface DerivedLaptop extends Laptop {
  gpu: LaptopGpu;
  /** Share of the GPU's rated TGP this machine allows, 0-1. */
  tgpRatio: number;
  effectivePerf: number;
  effectiveRt: number;
  /** How much performance is left on the table versus a full-power machine. */
  perfLostToTgp: number;
  perfPerDollar: number;
  perfPerInr: number;
  pixels: number;
}

export const DERIVED_LAPTOPS: DerivedLaptop[] = LAPTOPS.map((l) => {
  const gpu = LAPTOP_GPU_BY_ID[l.gpuId];
  const effectivePerf = perfAtTgp(gpu.perfAtMaxTgp, l.tgp, gpu.maxTgp);
  const effectiveRt = perfAtTgp(gpu.rtAtMaxTgp, l.tgp, gpu.maxTgp);
  const [w, h] = l.resolution.split(" x ").map(Number);
  return {
    ...l,
    gpu,
    tgpRatio: +(l.tgp / gpu.maxTgp).toFixed(3),
    effectivePerf,
    effectiveRt,
    perfLostToTgp: +(100 - (effectivePerf / gpu.perfAtMaxTgp) * 100).toFixed(0),
    perfPerDollar: +((effectivePerf / l.msrp) * 1000).toFixed(2),
    perfPerInr: +((effectivePerf / l.inr) * 100000).toFixed(2),
    pixels: w * h,
  };
});

export const LAPTOP_BRANDS: string[] = DERIVED_LAPTOPS.reduce<string[]>((acc, l) => {
  if (!acc.includes(l.brand)) acc.push(l.brand);
  return acc.sort();
}, []);

/** Laptop GPUs that at least one listed machine ships, in performance order. */
export const USED_LAPTOP_GPUS: LaptopGpu[] = LAPTOP_GPUS.filter((g) =>
  DERIVED_LAPTOPS.some((l) => l.gpuId === g.id),
).sort((a, b) => b.perfAtMaxTgp - a.perfAtMaxTgp);

export function laptopsForDesktopGpu(desktopId: string): DerivedLaptop[] {
  const families = LAPTOP_GPUS.filter((g) => g.desktopCousin === desktopId).map((g) => g.id);
  return DERIVED_LAPTOPS.filter((l) => families.includes(l.gpuId));
}
